import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const dist=path.resolve('dist');
function files(dir){return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?files(path.join(dir,e.name)):[path.join(dir,e.name)]);}
const assets=files(dist).filter(p=>!p.endsWith('sw.js')).sort();
const hash=crypto.createHash('sha256');for(const file of assets)hash.update(fs.readFileSync(file));
const version=hash.digest('hex').slice(0,16);
const urls=assets.map(p=>path.relative(dist,p).split(path.sep).join('/'));
fs.writeFileSync(path.join(dist,'sw.js'),`/* Generated by build.mjs: complete offline bank, including every question image. */
const CACHE = 'electrician-tiku-${version}';
const CORE = ${JSON.stringify(urls)};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(CORE.map(url => new Request(url,{cache:'reload'})))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith('electrician-tiku-') && key !== CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  const request=event.request, url=new URL(request.url);
  if(request.method!=='GET'||url.origin!==self.location.origin) return;
  event.respondWith(caches.open(CACHE).then(async cache => {
    if(request.mode==='navigate') return (await cache.match('index.html')) || fetch(request);
    const cached=await cache.match(request,{ignoreSearch:true});
    if(cached) return cached;
    return fetch(request);
  }));
});
`);
console.log(`Built ${urls.length} offline resources (${version})`);
